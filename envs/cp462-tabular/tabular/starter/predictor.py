"""สิ่งเดียวที่ระบบเรียก — แก้ไฟล์นี้กับ train.py แล้วส่งทั้งโฟลเดอร์

ระบบทำแค่นี้

    p = Predictor(config)
    y_pred = p.predict(X)      # X เป็น DataFrame **ดิบ** ไม่ผ่านการแปลงใดๆ

`X` มีคอลัมน์เหมือนข้อมูลที่คุณเทรน ยกเว้นคอลัมน์เป้าหมายที่ถูกตัดออก
· ลำดับคอลัมน์เหมือนกัน · dtype เหมือนกัน · **มีค่าว่างได้เหมือนกัน**

⚠️ **ทุกอย่างที่แปลงข้อมูลต้องอยู่ใน Pipeline** ไม่ใช่โค้ดที่คุณรันเองก่อนเทรน
ระบบส่งข้อมูลดิบเข้ามาตรงๆ · ขั้นตอนที่ทำนอก pipeline จะไม่มีใครทำให้ตอนทำนาย
แล้วโมเดลจะเห็นข้อมูลคนละรูปแบบกับที่เคยเห็น
"""

import joblib


class Predictor:
    def __init__(self, config: dict):
        # ไฟล์อยู่ในโฟลเดอร์เดียวกับไฟล์นี้เสมอ ไม่ต้องเดา path
        self.pipe = joblib.load("pipeline.pkl")

    def predict(self, X):
        """คืนอาเรย์ยาวเท่าจำนวนแถวของ `X`

        classification → label ของแต่ละแถว (ไม่ใช่ probability)
        regression     → ค่าตัวเลขของแต่ละแถว
        """
        return self.pipe.predict(X)
